/** Deterministic 12-week run series with a mild trend, seeded from the skill id. */
function weeklySeries(seed: string, base: number, trend: number): number[] {
  let h = 2166136261
  for (let i = 0; i < seed.length; i++) {
    h ^= seed.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  const out: number[] = []
  for (let w = 0; w < 12; w++) {
    h ^= h << 13
    h ^= h >>> 17
    h ^= h << 5
    const noise = (Math.abs(h) % 100) / 100 - 0.5
    out.push(Math.max(1, Math.round(base + trend * w + noise * base * 0.35)))
  }
  return out
}

