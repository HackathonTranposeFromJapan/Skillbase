export const skills: Skill[] = seeds.map(({ runBase, runTrend, ...rest }) => ({
  ...rest,
  source: sources[rest.id] ?? { kind: 'internal', team: rest.ownerTeam },
  access: access[rest.id] ?? { scope: 'company' },
  weeklyRuns: weeklySeries(rest.id, runBase, runTrend),
  usedBy: people.filter((p) => p.collection.includes(rest.id)).map((p) => p.id),
}))

export const skillsById: Record<string, Skill> = Object.fromEntries(
  skills.map((s) => [s.id, s]),
)

export const skillColor = (id: string): DitherColor => skillsById[id]?.color ?? 'grey'
